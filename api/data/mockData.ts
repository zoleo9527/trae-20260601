function makeHistory(
  id: string,
  reminderId: string,
  status: ReminderStatus,
  operatorId: string,
  action: string,
  remark: string,
  createdAt: string
): HistoryRecord {
  const u = userMap[operatorId];
  return {
    id,
    reminderId,
    status,
    operatorId,
    operatorName: u.name,
    operatorRole: u.role,
    action,
    remark,
    createdAt,
  };
}

function findByRole(role: UserRole): User[] {
  return mockUsers.filter((u) => u.role === role);
}

