function generateId(): string {
  return Math.random().toString(36).substring(2, 11)
}

function createStatusLog(
  status: string,
  operator: string,
  operatorRole: string,
  remark: string = ''
): StatusLog {
  return {
    id: generateId(),
    status: status as any,
    operator,
    operatorRole: operatorRole as any,
    timestamp: new Date(Date.now() - Math.random() * 86400000).toISOString(),
    remark,
  }
}

function createMealItems(): MealItem[] {
  return MEAL_ITEMS_TEMPLATE.map((item) => ({
    ...item,
    id: generateId(),
    quantity: Math.floor(Math.random() * 50) + 10,
    actualQuantity: Math.random() > 0.7
      ? Math.floor(Math.random() * 40) + 10
      : undefined,
    shortageQuantity: Math.random() > 0.8
      ? Math.floor(Math.random() * 10) + 1
      : undefined,
  }))
}

