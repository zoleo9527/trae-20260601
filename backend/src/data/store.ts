export interface DataStore {
  carSources: CarSource[];
  inspections: InspectionReport[];
  loans: LoanApplication[];
  orders: TransferOrder[];
  statusLogs: StatusChangeLog[];
  lastResetAt: string;
}

export const createDefaultStore = (): DataStore => ({
  carSources: JSON.parse(JSON.stringify(defaultCarSources)),
  inspections: JSON.parse(JSON.stringify(defaultInspections)),
  loans: JSON.parse(JSON.stringify(defaultLoans)),
  orders: JSON.parse(JSON.stringify(defaultOrders)),
  statusLogs: JSON.parse(JSON.stringify(defaultStatusLogs)),
  lastResetAt: now(),
});

export let store: DataStore = createDefaultStore();

export const resetStore = (): DataStore => {
  store = createDefaultStore();
  return store;
};

