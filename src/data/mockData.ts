const generateHistoryRecord = (
  action: string,
  operator: string,
  operatorRole: 'project_manager' | 'translator' | 'reviewer',
  remark: string,
  fromStatus?: string,
  toStatus?: string,
  daysAgo: number = 0
): HistoryRecord => {
  const date = new Date()
  date.setDate(date.getDate() - daysAgo)
  date.setHours(date.getHours() - Math.floor(Math.random() * 12))
  
  return {
    id: `hr-${Date.now()}-${Math.random().toString(36).substr(2, 9)}`,
    action,
    operator,
    operatorRole,
    timestamp: date.toISOString(),
    remark,
    fromStatus,
    toStatus,
  }
}

