function makeSeats(rows: number, cols: number, candidates: Candidate[]): ExamRoom["seats"] {
  const seats: ExamRoom["seats"] = []
  let ci = 0
  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) {
      const candidate = ci < candidates.length ? candidates[ci] : undefined
      seats.push({
        id: `seat-${r}-${c}`,
        row: r,
        col: c,
        candidateId: candidate?.id,
        candidateName: candidate?.name,
        status: candidate ? "assigned" : "empty",
      })
      ci++
    }
  }
  return seats
}

