function now(offsetMin = 0): string {
  return new Date(Date.now() - offsetMin * 60 * 1000).toISOString();
}

function mkEvent(
  complaintId: string,
  type: TimelineEvent['type'],
  operator: User,
  content: string,
  offsetMin: number,
  detail?: Record<string, unknown>,
): TimelineEvent {
  return {
    id: uid('e_'),
    complaintId,
    type,
    createdAt: now(offsetMin),
    operatorId: operator.id,
    operatorName: operator.name,
    operatorRole: operator.role,
    content,
    detail,
  };
}

