const generateItems = (seed: number, hasIssue: boolean = false): InspectionItem[] => {
  return inspectionItemTemplates.map((item, index) => {
    const result = hasIssue && index === 5 ? 'fail' : item.result;
    const remark = hasIssue && index === 5 ? '液压油管有轻微渗漏，需关注' : undefined;
    return {
      ...item,
      id: `item-${seed}-${index}`,
      result,
      remark,
      photos: result === 'fail' ? ['photo-placeholder'] : [],
    };
  });
};

const generateItemsWithMultipleFails = (seed: number): InspectionItem[] => {
  return inspectionItemTemplates.map((item, index) => {
    let result: 'pass' | 'fail' | 'na' = 'pass';
    let remark: string | undefined;
    if (index === 5) {
      result = 'fail';
      remark = '液压油管渗漏严重，需要更换密封件';
    }
    if (index === 8) {
      result = 'fail';
      remark = '安全带卡扣松动，存在安全隐患';
    }
    return {
      ...item,
      id: `item-${seed}-${index}`,
      result,
      remark,
      photos: result === 'fail' ? ['photo-placeholder'] : [],
    };
  });
};

